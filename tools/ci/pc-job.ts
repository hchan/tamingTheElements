/**
 * Renders the two shell scripts of a PC e2e job (job.sh, start.sh). They are uploaded to ~/tte-offload/jobs/<id>/ on
 * the PC and run there by tools/ci/pc-remote.ts; nothing is quoted through Windows (the upload is a tar stream).
 * Only $HOME-relative paths appear: no host, user, address or Mac path is ever rendered.
 * Exit codes written by job.sh: 92 bundle rejected, 93 killed by the memory guard, 95 busy (lock/load/RAM wait
 * timed out), 96 frame preflight, 97 clone missing or disk low, 98 sha unknown, 99 install failed, 124 hard timeout,
 * otherwise the command's own. Files next to job.sh: pgid, status.json, health.csv, output.log, out/.
 */
export type LaneName = 'short' | 'full';

export interface Lane {
  /** Clone dir, relative to ~/tte-offload. */
  clone: string;
  /** Lock file, relative to ~/tte-offload. */
  lock: string;
  port: number;
  /** TMPDIR for browsers, relative to ~/tte-offload (wiped per job). */
  tmp: string;
  workers: number;
  waitSec: number;
  hardSec: number;
}

export const LANES: Record<LaneName, Lane> = {
  short: { clone: 'lanes/short/tamingTheElements', lock: 'locks/short.lock', port: 7970, tmp: 'tmp/short', workers: 1, waitSec: 45 * 60, hardSec: 40 * 60 },
  full: { clone: 'tamingTheElements', lock: 'locks/full.lock', port: 7960, tmp: 'tmp/full', workers: 1, waitSec: 3 * 3600, hardSec: 4 * 3600 },
};

export interface JobSpec {
  id: string;
  lane: LaneName;
  source: { sha: string; ref?: string; sha256?: string; bundle?: string };
  /** argv run under browser-slot inside the clone, e.g. ['corepack','pnpm','e2e','--','--grep','a b']. */
  command: readonly string[];
  /** Extra env for the command (keys must be identifiers). */
  env: Readonly<Record<string, string>>;
  /** Paths (relative to the clone) copied into out/fetch/ after the run. */
  fetch: readonly string[];
  /** Run the frame preflight (exit 96 on a stall). */
  preflight: boolean;
  /** Worker count for the lane guards and, with `direct`, the --workers flag (default: the lane's). */
  workers?: number;
  /** Seconds to wait for the lane lock before exit 95 (default: the lane's waitSec). */
  waitSec?: number;
  /** The command is a direct `playwright test`: append reporter, trace, output and worker flags. */
  direct?: boolean;
}

/** POSIX single-quote one word. */
export function shellQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** The one job-id shape every PC tool accepts (pc-job, pc-snapshot, pc-remote; also what ctl.sh's case pattern allows). */
export const JOB_ID_RE = /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/;
const OUT_FLAG = '--output=$OUT/test-results';

export function renderJob(spec: JobSpec): { jobSh: string; startSh: string } {
  const { id, lane: laneName, source } = spec;
  if (!JOB_ID_RE.test(id)) throw new Error(`bad job id: ${id}`);
  for (const k of Object.keys(spec.env)) if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) throw new Error(`bad env key: ${k}`);
  const lane = LANES[laneName];
  const workers = spec.workers ?? lane.workers;
  const words = spec.command.map(shellQuote);
  if (spec.direct) {
    words.push(shellQuote(`--reporter=${laneName === 'short' ? 'list' : 'dot'},json,html`), shellQuote('--trace=retain-on-failure'), `"${OUT_FLAG}"`, shellQuote(`--workers=${workers}`));
  }
  const cmdLine = words.join(' ');
  const envLines = Object.entries(spec.env).map(([k, v]) => `export ${k}=${shellQuote(v)}`);
  const fetchLines = spec.fetch.map((p) => `  [ -e ${shellQuote(p)} ] && cp -R --parents ${shellQuote(p)} "$OUT/fetch/" 2>/dev/null`);
  const waitSec = spec.waitSec ?? lane.waitSec;
  if (!Number.isInteger(waitSec) || waitSec < 0) throw new Error(`bad waitSec: ${String(waitSec)}`);
  const minMemKb = `$(( (2048 + 1536 * ${workers}) * 1024 ))`;

  const fetchSource = source.ref
    ? [
        `if [ -f "$JOB/src.bundle" ]; then`,
        `  git bundle verify "$JOB/src.bundle" >/dev/null 2>&1 || { echo "bundle rejected (verify)"; fail 92; }`,
        `  [ "$(sha256sum "$JOB/src.bundle" | cut -d' ' -f1)" = ${shellQuote(source.sha256 ?? '')} ] || { echo "bundle rejected (sha256)"; fail 92; }`,
        `  git fetch -q "$JOB/src.bundle" +${shellQuote(source.ref)}:${shellQuote(source.ref)} || { echo "bundle rejected (fetch)"; fail 92; }`,
        `else echo "bundle missing"; fail 92; fi`,
      ]
    : [`# sha mode: the commit must already be on origin`];

  const jobSh = `#!/bin/bash
# PC e2e job ${id} (lane ${laneName}); generated by tools/ci/pc-job.ts. Runs on the PC inside WSL.
set -uo pipefail
# Become a process group leader so cancel (kill -TERM -<pgid>) and the guards reach every child.
[ "\${TTE_JOB_LEADER:-}" = 1 ] || exec env TTE_JOB_LEADER=1 setsid -w bash "$0" "$@"
export NVM_DIR=$HOME/.nvm; . "$NVM_DIR/nvm.sh" >/dev/null 2>&1
BASE=$HOME/tte-offload
JOB=$BASE/jobs/${id}
CLONE=$BASE/${lane.clone}
LOCK=$BASE/${lane.lock}
OUT=$JOB/out
PGID=$$
mkdir -p "$OUT/test-results" "$OUT/fetch" "$BASE/locks"
echo $$ > "$JOB/pgid"; cp "$JOB/pgid" "$JOB/pid"
T0=$SECONDS; TQ=0; TS=0; TR=0; SAMPLER=0
export TTE_E2E_LOCAL=1
export TMPDIR=$BASE/${lane.tmp}

status() { # state rc result
  local maxload; maxload=$(awk -F, 'NR>1 && $2>m {m=$2} END {print m+0}' "$JOB/health.csv" 2>/dev/null)
  printf '{"state":"%s","rc":%s,"result":"%s","queueSec":%s,"syncSec":%s,"runSec":%s,"maxLoad":%s}\\n' \\
    "$1" "$2" "$3" "$TQ" "$TS" "$TR" "\${maxload:-0}" > "$JOB/status.json.tmp" && mv "$JOB/status.json.tmp" "$JOB/status.json"
}
finish() { # rc: record status, stop helpers, kill stray browsers and children
  local rc=$1 res=error
  trap - EXIT INT
  trap '' TERM
  [ "$SAMPLER" -gt 0 ] && kill "$SAMPLER" 2>/dev/null
  [ -f "$JOB/killed-mem" ] && rc=93
  case $rc in 0) res=ok ;; 1) res=fail ;; esac
  pkill -f -- "--user-data-dir=$TMPDIR" 2>/dev/null
  status done "$rc" "$res"
  kill -TERM -- "-$PGID" 2>/dev/null
  exit "$rc"
}
fail() { finish "$1"; }
trap 'fail 143' TERM INT
trap 'finish $?' EXIT
status queued 0 pending

# 1. Queue: the lane lock, then the load, RAM and disk guards.
mkdir -p "$(dirname "$LOCK")" "$TMPDIR"
exec 9>"$LOCK"
until flock -w ${Math.min(60, waitSec)} 9; do
  echo "queued behind $(cat "$LOCK.holder" 2>/dev/null || echo unknown)"
  [ $((SECONDS - T0)) -ge ${waitSec} ] && { echo "PC busy: lock wait timed out"; fail 95; }
done
echo ${id} > "$LOCK.holder"
GW=$SECONDS
while :; do
  load=$(cut -d. -f1 /proc/loadavg)
  mem=$(awk '/MemAvailable/ {print $2}' /proc/meminfo)
  if [ "$load" -le 10 ] && [ "$mem" -ge ${minMemKb} ]; then break; fi
  [ $((SECONDS - GW)) -gt 1200 ] && { echo "PC busy: load $load, MemAvailable $mem kB"; fail 95; }
  sleep 15
done
[ "$(df -Pk "$HOME" | awk 'NR==2 {print $4}')" -ge 10485760 ] || { echo "PC disk under 10 GB free"; fail 97; }
TQ=$((SECONDS - T0)); T1=$SECONDS; status syncing 0 pending

# 2. Sync the source into the lane clone.
cd "$CLONE" || { echo "lane clone missing: ${lane.clone}"; fail 97; }
git fetch -q origin
${fetchSource.join('\n')}
git checkout -q --detach ${shellQuote(source.sha)} || { echo "commit unknown on the PC"; fail 98; }
${source.ref ? `git update-ref -d ${shellQuote(source.ref)} 2>/dev/null` : ':'}
git clean -fdq -e node_modules
corepack pnpm install --frozen-lockfile >/dev/null 2>&1 || { echo "pnpm install failed"; fail 99; }
corepack pnpm exec playwright install chromium >/dev/null 2>&1 || true
TS=$((SECONDS - T1))

# 3. Environment (the PC-safe one) and per-lane temp.
unset DISPLAY WAYLAND_DISPLAY
export E2E_PORT=${lane.port} E2E_PAGES_PORT=${lane.port + 1}
rm -rf "$TMPDIR"; mkdir -p "$TMPDIR"
export TTE_RESULTS=$OUT
export PLAYWRIGHT_HTML_OPEN=never
export PLAYWRIGHT_JSON_OUTPUT_FILE=$OUT/results.json
export PLAYWRIGHT_HTML_OUTPUT_DIR=$OUT/report PLAYWRIGHT_HTML_REPORT=$OUT/report
${envLines.join('\n')}

# 4. Frame preflight: a compositor stall is an error, not a test failure.
${spec.preflight ? `if [ -f tools/dev/pc-frame-check.cjs ]; then
  mkdir -p "$BASE/state"
  if node tools/dev/pc-frame-check.cjs; then touch "$BASE/state/frames-ok"; else touch "$BASE/state/frames-stall"; echo "ERROR: PC compositor is not producing frames (preflight)"; fail 96; fi
fi` : ':'}

# 5. Health sampler: every 30 s; kills the job group when MemAvailable stays under 1 GB twice.
echo "ts,load1,memavail_mb,gpu_temp,gpu_util" > "$JOB/health.csv"
(
  low=0
  while sleep 30; do
    mem=$(awk '/MemAvailable/ {print int($2/1024)}' /proc/meminfo)
    gpu=$(nvidia-smi --query-gpu=temperature.gpu,utilization.gpu --format=csv,noheader,nounits 2>/dev/null | tr -d ' ' | head -1)
    echo "$(date +%s),$(cut -d' ' -f1 /proc/loadavg),$mem,\${gpu:-,}" >> "$JOB/health.csv"
    if [ "$mem" -lt 1024 ]; then low=$((low + 1)); else low=0; fi
    if [ "$low" -ge 2 ]; then touch "$JOB/killed-mem"; kill -TERM -- "-$PGID" 2>/dev/null; fi
  done
) &
SAMPLER=$!

# 6. Run.
status running 0 pending
T2=$SECONDS
timeout -k 30 ${lane.hardSec} corepack pnpm exec tsx tools/ci/browser-slot.ts -- ${cmdLine}
RC=$?
TR=$((SECONDS - T2))
{
${fetchLines.length > 0 ? fetchLines.join('\n') : '  :'}
} || true
finish "$RC"
`;

  const startSh = `#!/bin/bash
# Starts job ${id}: detached by default (survives the ssh session), or in the foreground with "fg".
cd "$(dirname "$0")" || exit 3
mkdir -p out
if [ "\${1:-}" = fg ]; then
  bash job.sh 2>&1 | tee out/output.log
  exit "\${PIPESTATUS[0]}"
fi
setsid -f bash job.sh > out/output.log 2>&1 < /dev/null
echo started
`;
  return { jobSh, startSh };
}
