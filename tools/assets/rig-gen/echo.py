"""Procedural Echo rig parts + rig.json (air trickster: hooded graphite cloak with white concentric sound-wave rings, long tattered cloak tail, open palms, silver mask with two bright eyes). Original art generated by this
script (no legacy pixels used). Run: python3 tools/assets/rig-gen/echo.py <out_rig_dir>  (needs Pillow + numpy)
Look matches the Fiara/Pax/Treenoc/Morblass/Rokcore rigs: cel-banded ramp, dark outline, light upper-left rim. High contrast on purpose: near-black graphite cloak with white wave rings
so it reads on the bright Air floor (and the dark ones).
"""
