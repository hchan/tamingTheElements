import numpy as np
from PIL import Image, ImageDraw, ImageFilter
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import palette

OUT = sys.argv[1]
os.makedirs(os.path.join(OUT, "parts"), exist_ok=True)
SS = 4
W = 80 * SS
AIR = palette.ELEMENT_RAMPS["air"]
STORM = [(0.0, (6, 8, 12)), (0.3, (20, 26, 36)), (0.58, (42, 54, 72)), (0.82, (84, 100, 124)), (1.0, (148, 166, 188))]
BAND = [(0.0, (190, 210, 230)), (0.5, (226, 238, 248)), (1.0, (255, 255, 255))]
OUTLINE = np.array((2, 4, 8), np.float32)
RIM = np.array((230, 244, 255), np.float32)
FACE = (214, 226, 238)
EYE = (40, 150, 255)

# geometry in the 80x80 rest frame, E view (y down)
G = {
 "tail": dict(pts=[(18,50),(54,50),(60,62),(52,72),(44,78),(38,70),(30,78),(22,68),(14,62)], joint=(36,52), z=1, parent="torso", bias=-0.1),  # tattered cloak hem
 "armB": dict(pts=[(46,28),(56,28),(64,32),(70,40),(66,44),(58,38),(48,36)], joint=(50,31), z=2, parent="torso", bias=-0.18),
 "torso": dict(pts=[(16,24),(54,24),(60,36),(56,52),(46,56),(24,56),(14,44),(12,34)], joint=(36,40), z=5, parent=None, bias=0.0),
 "head": dict(pts=[(30,18),(34,6),(41,2),(48,6),(52,18),(50,28),(42,31),(34,28)], joint=(41,27), z=7, parent="torso", bias=0.08),
 "armF": dict(pts=[(14,28),(26,28),(30,38),(26,48),(16,50),(10,44),(10,34)], joint=(22,31), z=8, parent="torso", bias=0.1),
}

def view_tf(view, part):
    if view == "E":
        return dict(sx=1.0, dx=-3 if part == "head" else 0, dy=0)
    if view == "SE":
        d = dict(sx=0.93, dx=2, dy=1)
        if part == "head": d = dict(sx=1.06, dx=-8, dy=4, scale=1.06)
        if part == "armF": d = dict(sx=0.95, dx=-3, dy=1)
        if part == "armB": d = dict(sx=0.95, dx=3, dy=1)
        if part == "torso": d = dict(sx=0.96, dx=1, dy=2)
        return d
    d = dict(sx=0.93, dx=-1, dy=-1)  # NE: seen from behind
    if part == "head": d = dict(sx=0.92, dx=-6, dy=-2, scale=0.94)
    if part == "armF": d = dict(sx=0.95, dx=1, dy=-1)
    if part == "armB": d = dict(sx=0.95, dx=2, dy=-1)
    if part == "torso": d = dict(sx=1.0, dx=-2, dy=-1)
    return d

def apply(tf, p, c=(40, 40)):
    s = tf.get("scale", 1.0)
    return (c[0] + (p[0] - c[0]) * tf["sx"] * s + tf["dx"], c[1] + (p[1] - c[1]) * s + tf["dy"])

def noise(rs, scale, sx=1, sy=1):
    """Smooth noise, stretched sx/sy times (flow streaks)."""
    h = max(2, W // (scale * sy) + 2); w = max(2, W // (scale * sx) + 2)
    small = rs.rand(h, w)
    return np.asarray(Image.fromarray((small * 255).astype(np.uint8)).resize((W, W), Image.BICUBIC), np.float32) / 255.0

def render(name, view, pts, g, seed):
    m = Image.new("L", (W, W), 0)
    d = ImageDraw.Draw(m)
    d.polygon([(x * SS, y * SS) for x, y in pts], fill=255)
    m = m.filter(ImageFilter.GaussianBlur(SS * 0.35))
    ma = np.asarray(m, np.float32) / 255.0
    rs = np.random.RandomState(seed)
    coarse = noise(rs, 8); mid = noise(rs, 4); fine = noise(rs, 2)
    yy, xx = np.mgrid[0:W, 0:W].astype(np.float32) / W
    # cloak: pale concentric wave rings over a dark body, lit from the upper left
    cx = 0.45; ang = np.arctan2(yy - 0.45, xx - cx); rad = np.hypot(xx - cx, yy - 0.45)
    swirl = np.sin(rad * 34.0 + (mid - 0.5) * 2.0)  # concentric sound-wave rings
    t = 0.55 - 0.35 * yy - 0.2 * xx + 0.2 * (mid - 0.5) + 0.08 * (fine - 0.5) + g["bias"] + 0.15
    band = swirl > 0.8
    t = np.clip(np.round(np.clip(t, 0, 1) * 5.0) / 5.0, 0, 1)
    rgb = palette.ramp(STORM, t)
    lt = np.clip(np.round(np.clip(0.3 + 0.7 * (swirl - 0.8) / 0.2 + 0.2 * (fine - 0.5), 0, 1) * 3.0) / 3.0, 0, 1)
    rgb = np.where(band[..., None], palette.ramp(BAND, lt), rgb)
    inner = np.asarray(m.filter(ImageFilter.MinFilter(SS * 3 + 1)), np.float32) / 255.0
    edge = np.clip(np.subtract(ma, inner), 0, 1)
    shifted = np.roll(np.roll(ma, SS * 2, axis=0), SS * 2, axis=1)
    lit = np.clip(np.subtract(ma, shifted), 0, 1) * inner.clip(0, 1)
    lit = np.asarray(Image.fromarray((lit * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(SS * 0.5)), np.float32) / 255.0
    rgb = rgb * (1 - 1.0 * edge[..., None]) + OUTLINE[None, None, :] * (1.0 * edge[..., None])
    rgb = rgb * (1 - 0.7 * lit[..., None]) + RIM[None, None, :] * (0.7 * lit[..., None])
    return Image.fromarray(np.dstack([np.clip(rgb, 0, 255), ma * 255.0]).astype(np.uint8), "RGBA")

def face(im, tf, view):
    d = ImageDraw.Draw(im)
    x0, y0 = apply(tf, (36, 12)); x1, y1 = apply(tf, (48, 25))
    d.ellipse([x0 * SS, y0 * SS, x1 * SS, y1 * SS], fill=FACE + (255,), outline=tuple(int(v) for v in OUTLINE) + (255,), width=SS)  # silver mask
    for ex, ey in ((39.5, 18), (44.5, 18)):
        x, y = apply(tf, (ex, ey))
        d.ellipse([x * SS - 1.5 * SS, y * SS - 1.3 * SS, x * SS + 1.5 * SS, y * SS + 1.3 * SS], fill=EYE + (255,))

parts = []
for view in ("E", "SE", "NE"):
    tfs = {k: view_tf(view, k) for k in G}
    for k, g in G.items():
        pts = [apply(tfs[k], p) for p in g["pts"]]
        im = render(k, view, pts, g, zlib.crc32((k + view).encode()) % 9973 + 7)
        if k == "head" and view != "NE":
            face(im, tfs[k], view)
        small = im.resize((80, 80), Image.LANCZOS)
        a = np.asarray(small)
        ys, xs = np.nonzero(a[..., 3] > 8)
        x0, x1, y0, y1 = int(xs.min()), int(xs.max()) + 1, int(ys.min()), int(ys.max()) + 1
        crop = small.crop((x0, y0, x1, y1))
        fname = f"{k}.png" if view == "E" else f"{k}_{view.lower()}.png"
        crop.save(os.path.join(OUT, "parts", fname))
        parts.append(dict(view=view, id=k, png=fname, joint=apply(tfs[k], g["joint"]), off=(x0, y0), size=crop.size))

byv = {v: {e["id"]: e for e in parts if e["view"] == v} for v in ("E", "SE", "NE")}
def pv(e):
    return [int(round(e["joint"][0])) - e["off"][0], int(round(e["joint"][1])) - e["off"][1]]
def at(v, pid):
    g = G[pid]; e = byv[v][pid]
    jx, jy = int(round(e["joint"][0])), int(round(e["joint"][1]))
    if g["parent"] is None:
        return [jx, jy]
    pe = byv[v][g["parent"]]
    return [jx - int(round(pe["joint"][0])), jy - int(round(pe["joint"][1]))]

rig_parts = []
for pid in list(G):
    g = G[pid]
    p = {"id": pid}
    if g["parent"]: p["parent"] = g["parent"]
    p["png"] = byv["E"][pid]["png"]; p["pivot"] = pv(byv["E"][pid]); p["at"] = at("E", pid); p["z"] = g["z"]
    p["views"] = {v: {"png": byv[v][pid]["png"], "pivot": pv(byv[v][pid]), "at": at(v, pid)} for v in ("SE", "NE")}
    rig_parts.append(p)

