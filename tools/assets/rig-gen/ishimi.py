"""Procedural Ishimi rig parts + rig.json (slime circus performer: deep teal-navy gelatinous blob, bright cyan bubble sheen, puddle base, two blobby juggling lobes, big white googly eyes under a small jester tuft). Original art generated by this
script (no legacy pixels used). Run: python3 tools/assets/rig-gen/ishimi.py <out_rig_dir>  (needs Pillow + numpy)
Look matches the Fiara/Pax/Treenoc/Morblass/Rokcore rigs: cel-banded ramp, dark outline, light upper-left rim. High contrast on purpose: near-black teal body with bright cyan bubbles
so it reads on the mid-blue Water floor (and the others).
"""
