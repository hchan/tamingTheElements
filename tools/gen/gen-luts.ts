// Generates src/core/math/lut.generated.ts from the legacy rules fixture.
// Values are the exact doubles legacy Math.pow(1.1, L) produced under V8; never recomputed here.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

interface Entry {
  v: number;
  bits: string;
}

const root = resolve(import.meta.dirname, '../..');
const rules = JSON.parse(
  readFileSync(resolve(root, 'tests/fixtures/legacy/rules.json'), 'utf8'),
) as { levelScaling: { damageMultiplier: Record<string, Entry> } };

const lines: string[] = [];
for (let level = 0; level <= 20; level++) {
  const entry = rules.levelScaling.damageMultiplier[String(level)];
  if (!entry) throw new Error(`missing damageMultiplier level ${String(level)}`);
  const buf = new DataView(new ArrayBuffer(8));
  buf.setFloat64(0, entry.v);
  const bits = buf.getBigUint64(0).toString(16).padStart(16, '0');
  if (bits !== entry.bits) throw new Error(`bits mismatch at level ${String(level)}`);
  lines.push(`  ${String(entry.v)},`);
}

const out = `// GENERATED by tools/gen/gen-luts.ts from tests/fixtures/legacy/rules.json. Do not edit.
/** Legacy Math.pow(1.1, level) for level 0..20, as exact double literals. */
export const LEVEL_MULT: readonly number[] = [
${lines.join('\n')}
];
`;
writeFileSync(resolve(root, 'src/core/math/lut.generated.ts'), out);
